// 二代会话工具族（reserved2）：qq_get_prompt / 未读与最近消息 / 会话状态 / 已读 / 唤醒配置 /
// 发送（burst / message / poke）/ 等待消息 / 反馈 / 自己最近消息 / 消息详情 / 活跃成员 /
// 轻量记忆（memory_*）/ 黑话（slang_*）。
//
// 职责：把「一个会话」的全部可观测与可控面暴露给 agent，读写都通过桥接内部 Agent API
// （agentApi / agentApiLongPoll，带会话 token）。
//
// 明确不做：不直接连 OneBot、不实现鉴权（桥接侧校验 token 与模式）、不落盘任何状态。
//
// 状态归属：无模块级可变状态；cfg 用来判断工具开关与模式提示。依赖由入口注入。
//
// 接口约定：registerChatTools(server, ctx) —— 注册期同步调用一次；
// ctx = { cfg, agentApi, agentApiLongPoll, serializeModelData }。
import { z } from 'zod';

